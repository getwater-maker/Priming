'use strict';
/**
 * chapter-no.js — 📖 회목 번호 인식 한 곳(로이 2026-10-03).
 *   「제N회」(삼국지) · 「제N장」(빨간머리앤) · 「제N화」 형식의 제목에서 번호와 이름을 나눈다.
 *   예전엔 「제N회」만 알아봐서 「제N장」 책이 ① 제목 길이 기준(회목최대)에 번호까지 세어 오탐(「제16장 …」 24자) · 짧은제목을 무시했고
 *   ② 머리글 `제N장 짧은제목`·목차 번호 칸이 설정대로 안 나왔다. 제목 길이 기준·머리글·목차가 모두 이 정규식을 쓴다.
 *   m[1] = 「제N회」(번호) · m[2] = 회목 이름.
 */
const CH_RE = /^(제\s*\d+\s*[회장화])[.,]?\s*(.+)$/;
module.exports = { CH_RE };
